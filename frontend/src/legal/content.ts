export const LEGAL_NAV = [terms, privacy, refund].map(d => ({
  slug: d.slug,
  path: d.path,
  label: d.navLabel,
}))

export function legalSlugForPath(pathname: string): LegalSlug | null {
  const clean = pathname.replace(/\/+$/, '') || '/'
  const hit = Object.values(LEGAL_DOCS).find(d => d.path === clean)
  return hit ? hit.slug : null
}
